export const INDIA_STATES = Object.keys(INDIA_LOCATIONS);

/** Cities for the chosen state (case-insensitive); all cities when the state is unknown. */
export function citiesFor(state: string): string[] {
  const key = INDIA_STATES.find((s) => s.toLowerCase() === String(state || '').trim().toLowerCase());
  if (key) return INDIA_LOCATIONS[key];
  return Array.from(new Set(Object.values(INDIA_LOCATIONS).flat())).sort();
}

/** The state a city belongs to (first match), or '' when unknown. */
export function stateForCity(city: string): string {
  const c = String(city || '').trim().toLowerCase();
  if (!c) return '';
  return INDIA_STATES.find((s) => INDIA_LOCATIONS[s].some((x) => x.toLowerCase() === c)) || '';
}
